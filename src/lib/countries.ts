export function getFlagCdnSvgUrl(countryCode: string) {
  const code = countryCode.toLowerCase();

  if (!/^[a-z]{2}$/.test(code)) {
    return undefined;
  }

  return `https://flagcdn.com/${code}.svg`;
}

const generatedCountryOptions: CountryOption[] = isoCountryCodes.map((code) => ({
  code,
  name: stableCountryNames[code] ?? code,
  region: "All Countries",
  flagSvgUrl: getFlagCdnSvgUrl(code),
}));

export const countryOptions: CountryOption[] = [
  ...popularCountryOptions,
  ...generatedCountryOptions.filter(
    (country) =>
      !popularCountryOptions.some(
        (popularCountry) => popularCountry.code === country.code,
      ),
  ),
].map((country) => ({
  ...country,
  flagSvgUrl: country.flagSvgUrl ?? getFlagCdnSvgUrl(country.code),
}));

