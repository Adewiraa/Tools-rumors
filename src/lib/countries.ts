export function getCountryCodeFromName(countryName: string) {
  const key = countryName
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .trim()
    .toUpperCase()
    .replace(/[^A-Z0-9]+/g, "_")
    .replace(/^_+|_+$/g, "");

  return countryNameToCode[key] ?? key.slice(0, 2);
}
